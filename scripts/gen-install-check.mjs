// Writes backend/<project>/src/InstallCheck.js for each Apps Script project:
// every file's top-level functions, so checkInstall() (run from the Apps
// Script editor) can say which files are missing or out of date.
// Run after changing any backend file:  node scripts/gen-install-check.mjs
import fs from "fs";
import path from "path";
import vm from "vm";

// The same fingerprint checkInstall() computes in Apps Script: the
// function's own source without spaces, hashed. A function that differs is
// an old copy (or a second copy in another file that wins).
const fp = (src) => {
  const t = String(src).replace(/\s+/g, "");
  let h = 5381;
  for (let i = 0; i < t.length; i++) h = ((h * 33) ^ t.charCodeAt(i)) >>> 0;
  return h.toString(36);
};

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
// Tabs each project's spreadsheet must have (names of the SHEET_ variables
// in its code, so the check reads the exact tab names the code uses).
const SHEETS = {
  "vibration-analysis": ["SHEET_RMS_REG", "SHEET_SPM_REG", "SHEET_VIB_REGISTRY", "SHEET_VLOG", "SHEET_VENTRIES", "SHEET_VHIST", "SHEET_VLIMITS"],
};
for (const project of ["platform-core", "oil-lubrication", "vibration-analysis"]) {
  const dir = path.join(root, "backend", project, "src");
  const files = {};
  for (const f of fs.readdirSync(dir).sort()) {
    if (!f.endsWith(".js") || f === "InstallCheck.js") continue;
    const src = fs.readFileSync(path.join(dir, f), "utf8");
    const names = [...src.matchAll(/^function\s+([A-Za-z_$][\w$]*)\s*\(/gm)].map((m) => m[1]);
    if (!names.length) continue;
    // the source of each function exactly as V8 gives it back (toString)
    const ctx = vm.createContext({});
    vm.runInContext(names.map((n) => src.match(new RegExp("^function\\s+" + n.replace(/\$/g, "\\$") + "\\s*\\([\\s\\S]*?^\\}", "m"))[0]).join("\n"), ctx);
    files[f.replace(/\.js$/, "")] = Object.fromEntries(names.map((n) => [n, fp(vm.runInContext(n + ".toString()", ctx))]));
  }
  const out = `// GENERATED by scripts/gen-install-check.mjs — do not edit by hand.
//
// Install check: run checkInstall() from the Apps Script editor (pick it in
// the function list, then Run). The log lists every file of this project
// that is missing or out of date: a function not found, or found with other
// code (an old copy, or a second copy in another file that wins). A file
// pasted into the wrong place or only half pasted shows at once.
// After pasting fixes, publish a new version of the deployment.

var INSTALL_CHECK_FILES = ${JSON.stringify(files, null, 0).replace(/\},"/g, '},\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}")};

function checkInstall() {
  var g = (function () { return this; })() || globalThis;
  var fp = function (src) {
    var t = String(src).replace(/\\s+/g, ''), h = 5381;
    for (var i = 0; i < t.length; i++) h = ((h * 33) ^ t.charCodeAt(i)) >>> 0;
    return h.toString(36);
  };
  var missing = [], old = [], ok = 0, tabTrouble = false;
  Object.keys(INSTALL_CHECK_FILES).forEach(function (file) {
    var want = INSTALL_CHECK_FILES[file], names = Object.keys(want);
    var gone = names.filter(function (n) { return typeof g[n] !== 'function'; });
    var differ = names.filter(function (n) { return typeof g[n] === 'function' && fp(g[n].toString()) !== want[n]; });
    if (gone.length === names.length) missing.push(file);
    else if (gone.length || differ.length) old.push(file + ' (' + (gone.length ? 'not found: ' + gone.slice(0, 4).join(', ') + (gone.length > 4 ? ' …' : '') : '') +
      (gone.length && differ.length ? '; ' : '') + (differ.length ? 'other code: ' + differ.slice(0, 4).join(', ') + (differ.length > 4 ? ' …' : '') : '') + ')');
    else ok++;
  });
  var lines = ['${project}: ' + ok + ' of ' + Object.keys(INSTALL_CHECK_FILES).length + ' files OK.'];
  if (missing.length) lines.push('MISSING — add these files: ' + missing.join(', '));
  if (old.length) lines.push('OUT OF DATE — paste these files again (if a file is already new, another file holds an old copy of these functions: search the project for them and delete the old copy): ' + old.join('; '));
  // the spreadsheet's tabs the code needs (an empty or wrongly named tab
  // leaves pages empty: "Copy of …" after copying tabs between files)
  try {
    var ss = SpreadsheetApp.getActiveSpreadsheet();
    if (ss) {
      var need = ${JSON.stringify(SHEETS[project] || [])}.map(function (v) { return g[v]; }).filter(Boolean);
      var tabs = ss.getSheets().map(function (sh) { return sh.getName(); });
      var noTab = need.filter(function (n) { return tabs.indexOf(n) === -1; });
      var emptyTab = need.filter(function (n) { var sh = ss.getSheetByName(n); return sh && sh.getLastRow() < 2; });
      var copies = tabs.filter(function (n) { return /^Copy of /i.test(n); });
      tabTrouble = !!(noTab.length || emptyTab.length || copies.length);
      if (noTab.length) lines.push('TABS MISSING in this spreadsheet: ' + noTab.join(', '));
      if (emptyTab.length) lines.push('TABS EMPTY: ' + emptyTab.join(', '));
      if (copies.length) lines.push('Tabs still named "Copy of …" (rename them): ' + copies.join(', '));
      if (need.length && !noTab.length && !emptyTab.length) lines.push('All ' + need.length + ' main tabs found.');
    }
  } catch (e) {}
  // Platform Core: how big the equipment list answer is (a tab filled far
  // down makes the answer too big for the web app to hand back)
  if (typeof amRead_ === 'function') {
    try {
      var t = amRead_();
      var sh = t.sheet;
      var answer = JSON.stringify(listEquipmentMaster_({ orgId: 'ORG-ACC' }));
      lines.push('EQUIPMENT_MASTER: ' + t.rows.length + ' machines · data to row ' + sh.getLastRow() + ', column ' + sh.getLastColumn() +
        ' · sheet size ' + sh.getMaxRows() + ' rows × ' + sh.getMaxColumns() + ' columns · equipment list answer ' + Math.round(answer.length / 1024) + ' KB');
    } catch (e) { lines.push('EQUIPMENT_MASTER could not be read: ' + e.message); }
    // what the App Owner's Equipment & IDs page gets back (first page + total)
    try {
      var page = listEquipmentMaster_({ roles: ['ROLE-ADMIN'], orgId: 'ORG-ACC' }, { limit: 400, offset: 0 });
      lines.push('App Owner equipment list: ' + page.count + ' on the first page, total ' + (page.total === undefined ? 'NOT SENT (old AssetMaster.js / Code.js)' : page.total));
      var page2 = listEquipmentMaster_({ roles: ['ROLE-ADMIN'], orgId: 'ORG-ACC' }, { limit: 400, offset: 400 });
      lines.push('Second page (machines 401–800): ' + page2.count + ' machines, ' + Math.round(JSON.stringify(page2).length / 1024) + ' KB');
    } catch (e) { lines.push('App Owner equipment list failed: ' + e.message); }
    // App Owner accounts and their org (the org is in the login token: sign out and in after changing it)
    try {
      var owners = {};
      readSheetAsObjects_(getSheet_(SHEET_NAMES.USER_ROLES)).forEach(function (r) { if (r.RoleId === 'ROLE-ADMIN') owners[r.UserId] = true; });
      var who = readSheetAsObjects_(getSheet_(SHEET_NAMES.USERS)).filter(function (u) { return owners[u.UserId]; })
        .map(function (u) { return u.Email + ' (org "' + u.OrgId + '", ' + u.Status + ')'; });
      lines.push('App Owner accounts: ' + (who.join(', ') || 'none'));
    } catch (e) {}
  }
  // Vibration: how big and how slow the startup answers are (too big = the
  // pages stay empty: the app needs Code.js with the packed answers)
  if (typeof getStartupBundle === 'function' && typeof vbPackLists_ === 'function') {
    try {
      var t0 = Date.now();
      var bundle = getStartupBundle();
      var plainKb = Math.round(JSON.stringify(bundle).length / 1024);
      var packedKb = Math.round(JSON.stringify(vbPackLists_(bundle)).length / 1024);
      lines.push('Startup answer: ' + (bundle.vibPoints || []).length + ' VIB IDs, ' + (bundle.rmsRegister || []).length + ' RMS / ' + (bundle.spmRegister || []).length +
        ' SPM register rows · ' + plainKb + ' KB plain, ' + packedKb + ' KB packed · ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
    } catch (e) { lines.push('Startup answer failed: ' + e.message); }
    try {
      var t1 = Date.now();
      var lim = handleGetVibLimits({}, { email: 'install-check', roles: ['ROLE-ADMIN'], orgId: 'ORG-ACC' });
      lines.push('Limits answer: ' + (lim && lim.error ? 'ERROR ' + lim.error : Math.round(JSON.stringify(vbPackLists_(lim)).length / 1024) + ' KB packed') + ' · ' + ((Date.now() - t1) / 1000).toFixed(1) + ' s');
    } catch (e) { lines.push('Limits answer failed: ' + e.message); }
  } else if (typeof getStartupBundle === 'function' && typeof SHEET_VENTRIES !== 'undefined') { // Vibration only (Oil has its own getStartupBundle)
    lines.push('Code.js is OLD: it does not pack the answers, so the Vibration pages stay empty. Paste Code.js again.');
  }
  if (!missing.length && !old.length && !tabTrouble) lines.push('Everything is in place. Remember to publish a new version of the deployment.');
  var text = lines.join('\\n');
  Logger.log(text);
  return text;
}


// Run checkSecrets() from the editor (never over the web): the signing
// secret must be the same in all three projects, so compare these short
// fingerprints between them. The secret itself is never shown.
function checkSecrets() {
  var props = PropertiesService.getScriptProperties();
  var fpOf = function (v) {
    return Utilities.base64Encode(Utilities.computeDigest(Utilities.DigestAlgorithm.SHA_256, v, Utilities.Charset.UTF_8)).slice(0, 8);
  };
  var sec = props.getProperty('SESSION_SIGNING_SECRET');
  var pc = props.getProperty('PLATFORM_CORE_SPREADSHEET_ID');
  var text = '${project}\\n' +
    'SESSION_SIGNING_SECRET: ' + (sec ? 'fingerprint ' + fpOf(sec) + (sec !== sec.trim() ? ' — WARNING: spaces at the start or end' : '') : 'NOT SET') + '\\n' +
    'PLATFORM_CORE_SPREADSHEET_ID: ' + (pc ? 'set, ends …' + String(pc).trim().slice(-6) : 'NOT SET');
  Logger.log(text);
  return text;
}
`;
  fs.writeFileSync(path.join(dir, "InstallCheck.js"), out);
  console.log(project, Object.keys(files).length, "files");
}

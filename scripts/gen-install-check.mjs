// Writes backend/<project>/src/InstallCheck.js for each Apps Script project:
// every file's top-level functions, so checkInstall() (run from the Apps
// Script editor) can say which files are missing or out of date.
// Run after changing any backend file:  node scripts/gen-install-check.mjs
import fs from "fs";
import path from "path";
import vm from "vm";

// The same fingerprint checkInstall() computes in Apps Script: the
// function's own source without spaces, hashed. A function that differs is
// an old copy (or a second copy in another file that wins).
const fp = (src) => {
  const t = String(src).replace(/\s+/g, "");
  let h = 5381;
  for (let i = 0; i < t.length; i++) h = ((h * 33) ^ t.charCodeAt(i)) >>> 0;
  return h.toString(36);
};

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
for (const project of ["platform-core", "oil-lubrication", "vibration-analysis"]) {
  const dir = path.join(root, "backend", project, "src");
  const files = {};
  for (const f of fs.readdirSync(dir).sort()) {
    if (!f.endsWith(".js") || f === "InstallCheck.js") continue;
    const src = fs.readFileSync(path.join(dir, f), "utf8");
    const names = [...src.matchAll(/^function\s+([A-Za-z_$][\w$]*)\s*\(/gm)].map((m) => m[1]);
    if (!names.length) continue;
    // the source of each function exactly as V8 gives it back (toString)
    const ctx = vm.createContext({});
    vm.runInContext(names.map((n) => src.match(new RegExp("^function\\s+" + n.replace(/\$/g, "\\$") + "\\s*\\([\\s\\S]*?^\\}", "m"))[0]).join("\n"), ctx);
    files[f.replace(/\.js$/, "")] = Object.fromEntries(names.map((n) => [n, fp(vm.runInContext(n + ".toString()", ctx))]));
  }
  const out = `// GENERATED by scripts/gen-install-check.mjs — do not edit by hand.
//
// Install check: run checkInstall() from the Apps Script editor (pick it in
// the function list, then Run). The log lists every file of this project
// that is missing or out of date: a function not found, or found with other
// code (an old copy, or a second copy in another file that wins). A file
// pasted into the wrong place or only half pasted shows at once.
// After pasting fixes, publish a new version of the deployment.

var INSTALL_CHECK_FILES = ${JSON.stringify(files, null, 0).replace(/\},"/g, '},\n  "').replace(/^\{/, "{\n  ").replace(/\}$/, "\n}")};

function checkInstall() {
  var g = (function () { return this; })() || globalThis;
  var fp = function (src) {
    var t = String(src).replace(/\\s+/g, ''), h = 5381;
    for (var i = 0; i < t.length; i++) h = ((h * 33) ^ t.charCodeAt(i)) >>> 0;
    return h.toString(36);
  };
  var missing = [], old = [], ok = 0;
  Object.keys(INSTALL_CHECK_FILES).forEach(function (file) {
    var want = INSTALL_CHECK_FILES[file], names = Object.keys(want);
    var gone = names.filter(function (n) { return typeof g[n] !== 'function'; });
    var differ = names.filter(function (n) { return typeof g[n] === 'function' && fp(g[n].toString()) !== want[n]; });
    if (gone.length === names.length) missing.push(file);
    else if (gone.length || differ.length) old.push(file + ' (' + (gone.length ? 'not found: ' + gone.slice(0, 4).join(', ') + (gone.length > 4 ? ' …' : '') : '') +
      (gone.length && differ.length ? '; ' : '') + (differ.length ? 'other code: ' + differ.slice(0, 4).join(', ') + (differ.length > 4 ? ' …' : '') : '') + ')');
    else ok++;
  });
  var lines = ['${project}: ' + ok + ' of ' + Object.keys(INSTALL_CHECK_FILES).length + ' files OK.'];
  if (missing.length) lines.push('MISSING — add these files: ' + missing.join(', '));
  if (old.length) lines.push('OUT OF DATE — paste these files again (if a file is already new, another file holds an old copy of these functions: search the project for them and delete the old copy): ' + old.join('; '));
  if (!missing.length && !old.length) lines.push('Everything is in place. Remember to publish a new version of the deployment.');
  var text = lines.join('\\n');
  Logger.log(text);
  return text;
}

`;
  fs.writeFileSync(path.join(dir, "InstallCheck.js"), out);
  console.log(project, Object.keys(files).length, "files");
}
